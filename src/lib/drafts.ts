export function makeDraft(theme: string): DraftCell[] {
  const captions = themeCaptions[theme] ?? defaultCaptions
  return captions.map((caption, index) => ({ caption, visual: visuals[index % visuals.length] }))
}

export function titleForTopic(topic: string, theme: string): string {
  const cleanTopic = topic.trim().replace(/[。！？!?.]+$/u, '')
  if (!cleanTopic) return `${theme} · 日常表情`
  return cleanTopic.length > 20 ? `${cleanTopic.slice(0, 20)}…` : cleanTopic
}
